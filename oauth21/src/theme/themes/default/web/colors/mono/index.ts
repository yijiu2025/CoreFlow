/**
 * 黑白配色（mono）—— 属于 `themes/default/` 主题包，**电脑端**
 *
 * === 它在三级结构里的位置 ===
 * `themes/default/web/colors/mono/` 是**配色**：只换颜色 / 圆角 / 背景图，**不动 DOM**。
 * 它的上位 `themes/default/` 才是**主题包**（一套完整设计），本目录同级的
 * `themes/default/web/` 是这套设计在**电脑端**的版式。
 * 配色 id 以**目录名**为准（`mono`），URL `?theme=mono` 用的就是它。
 *
 * === 与移动端 mono 的关系：同 id，但两端各配各的 ===
 * 移动端也有一份 `mobile/colors/mono/`，两者的目录名相同、语义相同（都是"黑白基线"），
 * 但它们是**两条独立记录**（注册表里按 `包 × 设备` 分开存），互不影响：
 *   • `getThemeRecord('mono', 'mobile')` 取到的是移动端这份
 *   • `getThemeRecord('mono', 'web')`    取到的是电脑端这份
 * 这正是"手机端、电脑端分别配置主题"的落点 —— 同一套设计语言，两端可以给出不同的
 * 品牌色/圆角，而不必被迫保持一致。
 *
 * ⚠️ **配色 id 全局唯一**这条规则里，`mono` 是唯一的例外吗？不是 —— 它同样是
 *    全局唯一的：注册表以 id 为键，后加载的同名记录会被判重名而忽略。
 *    之所以两端都叫 mono 不冲突，是因为它们**本来就是同一个 id 的两端呈现**
 *    （注册表按 id 存一条，`device` 字段记它归哪端）；这也是为什么电脑端若要
 *    「海蓝」不能也叫 `ocean` —— 那才是真正的两个不同设计撞名。详见 `theme/index.ts`。
 *
 * ⚠️ 但它刻意**不给任何 token**：黑白档的色值就是电脑端样式表的基线本身。
 *    这是为了保住"零配色时渲染路径与没有主题机制时完全一致"这条不变量
 *    —— 基线明暗两档色值只存在于一个地方，不会与配色副本互相漂移。
 *
 * ⚠️ 明暗（浅色 / 深色 / 跟随系统）由 `theme/mode.ts` 管，与配色**正交**：
 *    `mono` 在浅色下是白底黑字、深色下是黑底白字，这是明暗维度在起作用，
 *    不是 mono 自己提供了两套色。所以这里同样不需要写 dark 变体。
 *
 * === 现状 ===
 * 电脑端核心组件（StandardLogin / MiniLogin / …）目前是**业务与 UI 揉在一起**的单体，
 * 尚未按「业务容器 + 版式」拆分，所以本套配色暂时**没有消费方**（不会被注入）。
 * 它的作用是先把三级结构的目录骨架立起来：容器重构落地后，`?theme=mono` 就会
 * 在电脑端自然生效，那时不需要再动本目录。
 *
 * @author yijiu2025
 */
