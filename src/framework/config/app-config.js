import { loadOverrides } from './overrides.js';

/** 静态覆盖（可选；缺失则为 {}）。一次加载，多处引用 */
const APP_CONFIG = loadOverrides('app_config.js', 'APP_CONFIG');

export { APP_CONFIG };
